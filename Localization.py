def tr(language, key, **kwargs):
    """Translate a key, falling back to English and finally the key itself."""
    table = STRINGS.get(language) or STRINGS["en"]
    text = table.get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError, IndexError):
            pass
    return text


def meme_taunt(language, index):
    lines = MEME_TAUNTS.get(language) or MEME_TAUNTS["en"]
    return lines[index % len(lines)]
